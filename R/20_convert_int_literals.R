#' Add Explicit Integer Suffix `L` to Integer Literals
#'
#' @description
#' Converts bare integer literals to explicit integer form with an `L` suffix,
#' e.g. `seq_len(10)` becomes `seq_len(10L)`. Strings and comments are left
#' unchanged, and a line can opt out with a `# rpkgkit: not int` comment (see
#' the section below).
#'
#' [convert_int_literals()] operates on one R file. When `path` is `NULL` and
#' RStudio is available, it uses the currently active document.
#' [package_convert_int_literals()] walks selected directories of an R package
#' and applies the same conversion to every `.R` / `.r` file found, except
#' files generated by `Rcpp::compileAttributes()` or `rextendr::document()`
#' (see `exclude`).
#'
#' @param path For [convert_int_literals()], a character string specifying the
#'   R file to modify. If `NULL` and RStudio is available, the currently active
#'   document path is used.
#'
#'   For [package_convert_int_literals()], a character string specifying the
#'   package root. If `NULL`, the current working directory is used.
#' @param verbose Logical; enable or disable per-file messages. Used only by
#'   [convert_int_literals()]. Default `TRUE`.
#' @param dirs Character vector of subdirectories relative to `path` to search.
#'   Used only by [package_convert_int_literals()]. Defaults to
#'   `c("R")`.
#' @param recursive Logical; recurse into subdirectories. Used only by
#'   [package_convert_int_literals()]. Default `TRUE`.
#' @param exclude Character vector of file names to skip, matched
#'   case-insensitively against the file base name. Used only by
#'   [package_convert_int_literals()]. Defaults to the auto-generated wrapper
#'   files `c("RcppExports.R", "extendr-wrappers.R")`. Use `NULL` (or
#'   `character()`) to process all files.
#' @param ... Additional arguments. Currently unused and must be empty.
#'
#' @return
#' [convert_int_literals()] invisibly returns the modified file path.
#' [package_convert_int_literals()] invisibly returns a character vector of
#' modified file paths.
#'
#' @details
#' A token is treated as an integer literal when it is:
#' - a decimal integer (`10`, `0`, `-` is not part of the token), or
#' - a hexadecimal integer (`0xFF`, `0X10`),
#'
#' and it is **not**:
#' - already suffixed with `L` / `l`,
#' - a floating-point number (`10.`, `1.0`, `.5`),
#' - scientific notation, including a signed exponent (`1e5`, `1e-3`, `1E-3`),
#' - a complex literal (`10i`),
#' - adjacent to an identifier character (`a-zA-Z0-9._`).
#'
#' @section Opting a line out:
#' Adding `L` changes the type of a literal, so some expressions must keep
#' their double literals (`2^31`, `2147483648`, `1e9 * 4`). Write a
#' `# rpkgkit: not int` comment on the line just above such a line, and every
#' literal on that line is left untouched:
#'
#' ```r
#' # rpkgkit: not int
#' y <- 2^31
#' ```
#'
#' The marker covers the immediately following line only, so a block needs one
#' marker per line. It is matched case-insensitively and tolerates extra
#' spaces, but it has to be the only thing on its line: a trailing
#' `x <- 1 # rpkgkit: not int` opts nothing out.
#'
#' @examples
#' \dontrun{
#' # --- Single file ---
#' temp <- tempfile(fileext = ".R")
#' writeLines("tmp <- seq_len(10)", temp)
#' convert_int_literals(temp)
#' readLines(temp)
#' # "tmp <- seq_len(10L)"
#'
#' # --- Opting a line out ---
#' writeLines(c("# rpkgkit: not int", "y <- 2^31"), temp)
#' convert_int_literals(temp)
#' readLines(temp)
#' # "# rpkgkit: not int" "y <- 2^31"
#'
#' # --- Entire package ---
#' tmp_pkg <- tempdir()
#' usethis::create_package(tmp_pkg, open = FALSE)
#' writeLines("foo <- seq_len(42)", file.path(tmp_pkg, "R/foo.R"))
#' package_convert_int_literals(tmp_pkg)
#' readLines(file.path(tmp_pkg, "R/foo.R"))
#' }
#'
#' @name convert_int_literals
NULL

#' @rdname convert_int_literals
#' @export
convert_int_literals <- function(path = NULL, verbose = TRUE, ...) {
  rlang::check_dots_empty0(...)
  rlang::check_bool(verbose)

  path <- path %||%
    if (rstudioapi::isAvailable()) rstudioapi::getActiveDocumentContext()$path
  if (!rlang::is_string(path) || !nzchar(path)) {
    cli::cli_abort(c("x" = "{.arg path} is required"))
  }

  .cil_convert_file(path, verbose = verbose)

  invisible(path)
}

#' Internal: rewrite the integer literals of one file
#'
#' Reads `path` once, rewrites it and writes it back only when something
#' changed, so already-converted files keep their modification time.
#'
#' @param path Character string; path to an R file.
#' @param verbose Logical; report the outcome with `cli`.
#'
#' @return `TRUE` when the file was rewritten, `FALSE` otherwise.
#'
.cil_convert_file <- function(path, verbose = FALSE) {
  text <- readLines(path, warn = FALSE)
  original <- paste(text, collapse = "\n")

  parse_safely(text = original, path = path)

  result <- .cil_process_text(original)
  changed <- !identical(result, original)

  if (changed) {
    writeLines(result, path)
  }

  if (verbose) {
    if (changed) {
      cli::cli_alert_success(
        "Added explicit integer suffixes in {.file {path}}"
      )
    } else {
      cli::cli_alert_info(
        "No integer literals to convert in {.file {path}}"
      )
    }
  }

  changed
}


#' Internal: character-level integer-literal rewrite (implemented in Rust)
#'
#' The character state machine (strings, raw strings, comments, hex/decimal
#' literals, signed exponents and the `# rpkgkit: not int` opt-out) now lives in
#' `cil_process_text_rs()`.
#'
#' @keywords internal
.cil_process_text <- function(text) {
  cil_process_text_rs(text)
}
