#' Enrich the YAML header of ONE Rmd file using the package DESCRIPTION
#'
#' Optimizes the YAML header of a single README.Rmd or vignette. Package
#' metadata (Package / Title / Version / Authors@R / Date / Language) is read
#' with the desc package from the DESCRIPTION found by walking up from `path`.
#'
#' Compatibility rules (the usethis template is treated as the "default"):
#' - A field that still has its usethis default value (title "Untitled" or equal
#'   to the file name, a bare `output: html_document` /
#'   `output: rmarkdown::html_vignette`, an "Untitled" VignetteIndexEntry) is
#'   replaced by an enriched value.
#' - A field the user has changed is kept. For `output`, the user's options are
#'   merged on top of the enriched defaults (user values always win), and other
#'   output formats (pdf_document, word_document, ...) are left untouched.
#' - Fields that usethis never writes (author, date, params, bibliography,
#'   knit, css, ...) are kept exactly as written when present, and only filled
#'   in when missing.
#' - Headers containing `!expr` in `output` are never rewritten.
#'
#' @param path Path to an Rmd file. If `NULL`, the file open in the active
#'   RStudio editor is used.
#' @param type "auto" (README.Rmd is a readme, everything else a vignette),
#'   "readme" or "vignette".
#' @param readme_format Format used when a README has the default output:
#'   "gfm" (md_document + variant: gfm), "github_document" or "html".
#' @param date "auto" -> `r Sys.Date()`; "desc" -> DESCRIPTION Date field;
#'   "none" -> do not add a date.
#' @param extra Named list of extra YAML fields added to the file. It is merged
#'   onto the built-in defaults with [utils::modifyList()] (nested lists are
#'   merged recursively, your values win). Built-in default: RStudio
#'   `editor_options` (`markdown: wrap: sentence`,
#'   `chunk_output_type: console`). To drop a default, set it to NULL, e.g.
#'   `list(editor_options = NULL)`.
#' @param extra_readme,extra_vignette Same as `extra`, but only applied when
#'   the file is a README / a vignette. Merge order (later wins): built-in
#'   defaults -> `extra` -> `extra_readme` / `extra_vignette`. Built-in README
#'   default: `always_allow_html: true`.
#'
#'   Extra fields never overwrite a key that already exists in the header;
#'   they are only added when missing. A key that is also generated by default
#'   (e.g. `lang`, `date`, `author`) replaces the generated value.
#' @return `TRUE` if the file was changed, `FALSE` otherwise (invisibly).
#' @examples
#' @export
#' \dontrun{
#' optimize_rmd_yaml()                          # active RStudio document
#' optimize_rmd_yaml("vignettes/intro.Rmd")
#' optimize_rmd_yaml("README.Rmd", readme_format = "github_document")
#' }
optimize_rmd_yaml <- function(
  path = NULL,
  type = c("auto", "readme", "vignette"),
  readme_format = c("gfm", "github_document", "html"),
  date = c("auto", "desc", "none"),
  extra = NULL,
  extra_readme = NULL,
  extra_vignette = NULL
) {
  type <- match_arg(type)
  readme_format <- match_arg(readme_format)
  date <- match_arg(date)

  rlang::check_installed(c("desc", "yaml"))

  path <- path %||%
    if (rstudioapi::isAvailable()) {
      rstudioapi::getActiveDocumentContext()$path
    }
  if (is.null(path) || !nzchar(path)) {
    cli::cli_abort(c("x" = "{.arg path} is required"))
  }
  if (!file.exists(path) || !grepl("\\.[Rr]md$", path)) {
    cli::cli_abort(c(
      "x" = "{.arg path} must be an existing Rmd file: {.path {path}}"
    ))
  }
  path <- normalizePath(path, mustWork = TRUE)

  if (type == "auto") {
    type <- .ory_detect_type(path)
  }
  extra_now <- .ory_extra_by_type(extra, extra_readme, extra_vignette)[[type]]
  meta <- .ory_meta(dirname(path))

  changed <- .ory_process_file(path, type, meta, readme_format, date, extra_now)
  if (changed) {
    cli::cli_alert_success("Updated YAML header of {.file {basename(path)}}")
  } else {
    cli::cli_alert_info("{.file {basename(path)}} is already optimized")
  }
  invisible(changed)
}


# =========================== Internal helpers ===============================
# Validate a user-supplied "extra fields" list
.ory_check_extra <- function(x, arg) {
  if (is.null(x)) {
    return(list())
  }
  if (
    !is.list(x) ||
      (length(x) && (is.null(names(x)) || !all(nzchar(names(x)))))
  ) {
    cli::cli_abort("`arg` must be a {.cls named list}")
  }
  x
}

# (later wins, NULL removes a key)
.ory_extra_by_type <- function(extra, extra_readme, extra_vignette) {
  extra <- .ory_check_extra(extra, "extra")
  extra_readme <- .ory_check_extra(extra_readme, "extra_readme")
  extra_vignette <- .ory_check_extra(extra_vignette, "extra_vignette")

  default_extra <- list(
    editor_options = list(
      markdown = list(wrap = "sentence"),
      chunk_output_type = "console"
    )
  )
  default_readme <- list(always_allow_html = TRUE)
  default_vignette <- list()

  list(
    readme = Reduce(
      utils::modifyList,
      list(default_extra, default_readme, extra, extra_readme)
    ),
    vignette = Reduce(
      utils::modifyList,
      list(default_extra, default_vignette, extra, extra_vignette)
    )
  )
}

.ory_detect_type <- function(path) {
  if (tolower(basename(path)) == "readme.rmd") "readme" else "vignette"
}

# Metadata from DESCRIPTION
.ory_meta <- function(pkg) {
  d <- desc::desc(file = pkg)
  list(
    package = d$get_field("Package"),
    title = d$get_field("Title", default = NA_character_),
    version = as.character(d$get_version()),
    authors = .ory_get_author_names(d),
    date = d$get_field("Date", default = NA_character_),
    lang = d$get_field("Language", default = "en-US") # English by default
  )
}

# Rewrite one file; returns TRUE if it changed
.ory_process_file <- function(path, type, meta, readme_format, date, extra) {
  rmd <- .ory_read_rmd(path)
  new_header <- .ory_build_header(
    rmd$header,
    path,
    type,
    meta,
    readme_format,
    date,
    extra
  )
  new_lines <- c(
    "---",
    new_header,
    "---",
    if (length(rmd$body) && nzchar(trimws(rmd$body[1L]))) "",
    rmd$body
  )

  if (identical(enc2utf8(new_lines), enc2utf8(rmd$raw))) {
    return(FALSE)
  }
  writeLines(enc2utf8(new_lines), path, useBytes = TRUE)
  TRUE
}

# Authors: people with role aut/cre in Authors@R; fall back to Author field
.ory_get_author_names <- function(d) {
  p <- tryCatch(d$get_authors(), error = function(e) NULL)
  if (!is.null(p) && length(p)) {
    keep <- vapply(
      unclass(p),
      function(x) any(c("aut", "cre") %in% x$role),
      logical(1L)
    )
    if (any(keep)) {
      nm <- format(p[keep], include = c("given", "family"))
      return(paste(nm, collapse = ", "))
    }
  }
  a <- d$get_field("Author", default = NA_character_)
  if (is.na(a)) {
    return(NULL)
  }
  trimws(gsub("\\[[^]]*\\]|<[^>]*>", "", a))
}

# Split an Rmd into YAML header lines and body lines
.ory_read_rmd <- function(path) {
  lines <- readLines(path, encoding = "UTF-8", warn = FALSE)
  header <- character()
  body <- lines
  if (length(lines) && grepl("^---\\s*$", lines[1L])) {
    end <- grep("^(---|\\.\\.\\.)\\s*$", lines)
    end <- end[end > 1L]
    if (length(end)) {
      e <- end[1L]
      header <- if (e > 2L) lines[2L:(e - 1L)] else character()
      body <- if (e < length(lines)) {
        lines[(e + 1L):length(lines)]
      } else {
        character()
      }
      if (length(body) && !nzchar(trimws(body[1L]))) body <- body[-1L]
    }
  }
  list(header = header, body = body, raw = lines)
}

# Split the header into top-level key chunks, keeping the original text
.ory_split_chunks <- function(h) {
  if (!length(h)) {
    return(list())
  }
  key_re <- "^[A-Za-z_][A-Za-z0-9_.-]*\\s*:"
  is_key <- grepl(key_re, h)
  if (!any(is_key)) {
    return(list())
  }
  grp <- cumsum(is_key)
  grp[grp == 0L] <- 1L
  keys <- sub("^([A-Za-z_][A-Za-z0-9_.-]*)\\s*:.*$", "\\1", h[is_key])
  chunks <- split(h, grp)
  names(chunks) <- keys
  chunks
}

# Double-quoted YAML scalar
.ory_yq <- function(x) {
  x <- gsub("\\\\", "\\\\\\\\", x)
  x <- gsub("\"", "\\\\\"", x)
  paste0("\"", x, "\"")
}

# Serialize an R list to YAML lines (logicals as true/false)
.ory_emit_yaml <- function(x) {
  txt <- yaml::as.yaml(
    x,
    indent = 2L,
    handlers = list(logical = function(v) {
      r <- ifelse(v, "true", "false")
      class(r) <- "verbatim"
      r
    })
  )
  strsplit(txt, "\n", fixed = TRUE)[[1L]]
}

# Enriched default options for each output format we manage
.ory_format_defaults <- function(fmt) {
  switch(
    fmt,
    "rmarkdown::html_vignette" = ,
    "html_vignette" = list(
      toc = TRUE,
      toc_depth = 3L,
      number_sections = TRUE,
      fig_caption = TRUE,
      df_print = "kable"
    ),
    "html_document" = list(
      toc = TRUE,
      toc_float = TRUE,
      theme = "cosmo",
      df_print = "paged"
    ),
    "github_document" = list(html_preview = FALSE),
    "md_document" = list(variant = "gfm"),
    NULL
  )
}

# Deep merge: values in `over` (user) win; missing keys are filled from `base`
.ory_merge_list <- function(over, base) {
  for (n in names(base)) {
    if (!n %in% names(over)) {
      over[n] <- list(base[[n]])
    } else if (is.list(over[[n]]) && is.list(base[[n]])) {
      over[[n]] <- .ory_merge_list(over[[n]], base[[n]])
    }
  }
  over
}

# Default output block (used when output is missing or still the usethis default)
.ory_default_output <- function(type, readme_format) {
  fmt <- if (type == "vignette") {
    "rmarkdown::html_vignette"
  } else {
    c(
      gfm = "md_document",
      github_document = "github_document",
      html = "html_document"
    )[[readme_format]]
  }
  out <- list()
  out[[fmt]] <- .ory_format_defaults(fmt)
  .ory_emit_yaml(list(output = out))
}

# Compare the existing output block with the usethis default and merge user
# changes. Returns: NULL  -> still the usethis default, use enriched default
#                   lines -> the (possibly merged) block to keep
.ory_optimize_output <- function(chunk, type) {
  if (any(grepl("!expr", chunk, fixed = TRUE))) {
    return(chunk)
  }
  parsed <- tryCatch(
    yaml::yaml.load(paste(chunk, collapse = "\n")),
    error = function(e) NULL
  )
  out <- if (is.list(parsed)) parsed[["output"]] else NULL

  usethis_default <- if (type == "vignette") {
    c("rmarkdown::html_vignette", "html_vignette")
  } else {
    c("html_document", "github_document", "md_document")
  }

  # Bare scalar: default -> enrich; another format (pdf_document...) -> keep
  if (is.character(out) && length(out) == 1L) {
    return(if (out %in% usethis_default) NULL else chunk)
  }
  if (!is.list(out) || is.null(names(out)) || !all(nzchar(names(out)))) {
    return(chunk)
  }

  merged <- out
  for (nm in names(out)) {
    def <- .ory_format_defaults(nm)
    if (is.null(def)) {
      next
    } # unmanaged format: untouched
    cur <- out[[nm]]
    if (is.null(cur) || identical(cur, "default")) {
      merged[nm] <- list(def)
    } else if (is.list(cur)) {
      merged[nm] <- list(.ory_merge_list(cur, def)) # user options win
    }
  }
  if (identical(merged, out)) {
    return(chunk)
  } # nothing to add: keep text
  .ory_emit_yaml(list(output = merged))
}

# Default title when the file has none (or only the usethis placeholder)
.ory_default_title <- function(path, type, meta) {
  if (type == "readme") {
    if (is.na(meta$title)) {
      return(meta$package)
    }
    return(paste0(meta$package, ": ", meta$title))
  }
  base <- tools::file_path_sans_ext(basename(path))
  if (identical(base, meta$package)) {
    return(paste("Introduction to", meta$package))
  }
  tools::toTitleCase(gsub("[-_.]+", " ", base))
}

# Build the new YAML header (lines without the --- fences)
.ory_build_header <- function(
  header,
  path,
  type,
  meta,
  readme_format,
  date,
  extra = list()
) {
  chunks <- .ory_split_chunks(header)
  has <- function(k) k %in% names(chunks)
  val <- function(k) trimws(sub("^[^:]+:\\s*", "", chunks[[k]][1L]))
  unq <- function(x) gsub("^[\"']|[\"']$", "", x)
  keep_or <- function(k, new) if (has(k)) chunks[[k]] else new

  managed <- c(
    "title",
    "subtitle",
    "author",
    "date",
    "lang",
    "output",
    "bibliography",
    "link-citations",
    "vignette"
  )

  # -- title: missing, "Untitled" or equal to the file name = usethis default
  base <- tools::file_path_sans_ext(basename(path))
  old_title <- if (has("title")) unq(val("title")) else NA_character_
  title_is_default <- !has("title") || old_title %in% c("", "Untitled", base)
  title_txt <- if (title_is_default) {
    .ory_default_title(path, type, meta)
  } else {
    old_title
  }

  # -- output: compare with usethis default, merge user changes
  out_lines <- if (has("output")) {
    .ory_optimize_output(chunks[["output"]], type)
  } else {
    NULL
  }
  if (is.null(out_lines)) {
    out_lines <- .ory_default_output(type, readme_format)
  }

  # -- bibliography: add automatically when a .bib sits next to the file
  bib <- list.files(dirname(path), pattern = "\\.bib$")
  bib_new <- if (!has("bibliography") && length(bib)) {
    c(paste0("bibliography: ", bib[1L]), "link-citations: true")
  }

  # -- vignette block: sync IndexEntry only if it still holds the default
  vig <- NULL
  if (type == "vignette") {
    if (!has("vignette")) {
      vig <- c(
        "vignette: >",
        paste0("  %\\VignetteIndexEntry{", title_txt, "}"),
        "  %\\VignetteEngine{knitr::rmarkdown}",
        "  %\\VignetteEncoding{UTF-8}"
      )
    } else {
      vig <- chunks[["vignette"]]
      i <- grep("VignetteIndexEntry", vig, fixed = TRUE)
      if (length(i) == 1L && i > 1L) {
        entry <- sub(".*VignetteIndexEntry\\{([^}]*)\\}.*", "\\1", vig[i])
        if (title_is_default && entry %in% c("", "Untitled", old_title)) {
          indent <- sub("^(\\s*).*$", "\\1", vig[i])
          vig[i] <- paste0(indent, "%\\VignetteIndexEntry{", title_txt, "}")
        }
      }
    }
  }

  out <- list(
    title = if (title_is_default) {
      paste0("title: ", .ory_yq(title_txt))
    } else {
      chunks[["title"]]
    },
    subtitle = if (type == "vignette") {
      keep_or(
        "subtitle",
        paste0("subtitle: ", .ory_yq(paste(meta$package, meta$version)))
      )
    },
    author = keep_or(
      "author",
      if (!is.null(meta$authors)) {
        paste0("author: ", .ory_yq(meta$authors))
      }
    ),
    date = keep_or(
      "date",
      switch(
        date,
        auto = "date: \"`r Sys.Date()`\"",
        desc = if (!is.na(meta$date)) {
          paste0("date: ", .ory_yq(meta$date))
        } else {
          "date: \"`r Sys.Date()`\""
        },
        none = NULL
      )
    ),
    lang = keep_or("lang", paste0("lang: ", meta$lang)),
    output = out_lines,
    bibliography = if (has("bibliography")) {
      chunks[["bibliography"]]
    } else {
      bib_new[1L]
    },
    `link-citations` = if (has("link-citations")) {
      chunks[["link-citations"]]
    } else {
      bib_new[2L]
    },
    vignette = vig
  )

  # Custom extra fields: only added when the key is absent from the header.
  # A key that is also generated by default replaces the generated value.
  for (k in names(extra)) {
    if (has(k)) {
      next
    }
    out[k] <- list(.ory_emit_yaml(extra[k]))
  }

  # Any other user field (params, knit, css, ...) is kept as written
  others <- chunks[setdiff(names(chunks), managed)]
  unlist(c(Filter(Negate(is.null), out), others), use.names = FALSE)
}
